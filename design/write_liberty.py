#!/usr/bin/env python3
"""Write layout/A7S_75t_R_structural.lib, the structural Liberty view.

Pins, directions, functions and areas only. No timing tables, no power, no pin
capacitance: timing Liberty stays stretch under decision 0002. Pin names and
order come from the CDL .SUBCKT lines, areas from the GDS BOUNDARY box, and the
function strings below are verified against design/check_cdl_function.py's
truth table by design/check_liberty.py. Output is deterministic (sorted cells,
no timestamps). Predictive-PDK view; nothing here is a measured part.

usage: python3 -I design/write_liberty.py [out.lib]
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import liberty_common as lc  # noqa: E402

# Liberty function of the single output pin of each combinational cell.
FUNC = {
    "INVx1": "!A",
    "BUFx1": "A",
    "NAND2x1": "!(A&B)",
    "NAND3x1": "!(A&B&C)",
    "NOR2x1": "!(A|B)",
    "NOR3x1": "!(A|B|C)",
    "AND2x1": "(A&B)",
    "OR2x1": "(A|B)",
    "AOI21x1": "!((A1&A2)|B)",
    "OAI21x1": "!((A1|A2)&B)",
    "AOI22x1": "!((A1&A2)|(B1&B2))",
    "OAI22x1": "!((A1|A2)&(B1|B2))",
    "XOR2x1": "(A^B)",
    "XNOR2x1": "!(A^B)",
    "TIEHIx1": "1",
    "TIELOx1": "0",
}
# Cells with no devices and no function: area only, dont_use.
AREA_ONLY = ["FILLER1", "FILLER2", "FILLER4", "TAP"]
# Never offered to abc; tie cells are reached through hilomap instead.
DONT_USE = {"TIEHIx1", "TIELOx1"} | set(AREA_ONLY)
SEQ = {"DFFHQNx1", "DHLx1"}
OUTPUTS = {"Y", "H", "L", "Q", "QN"}


def cell_text(cell):
    area = lc.boundary_area_um2(cell)
    out = ["  cell (%s%s) {" % (cell, lc.SUFFIX), "    area : %.6f;" % area]
    if cell in DONT_USE:
        out.append("    dont_use : true;")
    if cell == "DFFHQNx1":
        # IQN holds the inverted captured D; QN is that state (CDL: QN = !D)
        out += ['    ff (IQN, IQ) {', '      clocked_on : "CLK";', '      next_state : "!D";', "    }"]
    elif cell == "DHLx1":
        out += ['    latch (IQ, IQN) {', '      enable : "CLK";', '      data_in : "D";', "    }"]
    if cell not in AREA_ONLY:
        for pin in lc.cdl_pins(cell):
            if pin in ("VDD", "VSS"):
                continue
            out.append("    pin (%s) {" % pin)
            if pin in OUTPUTS:
                fn = FUNC.get(cell) or {"DFFHQNx1": "IQN", "DHLx1": "IQ"}[cell]
                out += ["      direction : output;", '      function : "%s";' % fn]
            else:
                out.append("      direction : input;")
                if cell in SEQ and pin == "CLK":
                    out.append("      clock : true;")
            out.append("    }")
    out.append("  }")
    return out


def render():
    cells = sorted(set(lc.load_fn()) | SEQ | set(AREA_ONLY))
    head = [
        "/* Structural Liberty for the A7S_75t_R library: pins, directions, functions",
        "   and areas only. No timing, power or capacitance. Generated by",
        "   design/write_liberty.py; do not edit. Predictive 7 nm PDK; not a measured part. */",
        "library (%s) {" % lc.LIB_NAME,
        "  delay_model : table_lookup;",
        '  time_unit : "1ps";',
        '  voltage_unit : "1V";',
        '  current_unit : "1uA";',
        '  capacitive_load_unit (1, ff);',
        '  pulling_resistance_unit : "1kohm";',
    ]
    body = [l for c in cells for l in cell_text(c)]
    return "\n".join(head + body + ["}"]) + "\n"


def main():
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else lc.LIB_PATH
    out.write_text(render())
    print(out)


if __name__ == "__main__":
    main()
